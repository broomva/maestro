//! BRO-3636: a flow's driver skill, generated from its compiled IR. The committed skill for
//! verify@1 is what the generator gives now, and the order of its steps is the IR's dependency
//! order, whatever the order of the definition or of the ids.

use maestro_flow::driver::{self, skill_name, steps};
use maestro_flow::kernel::compile;

const VERIFY: &str = include_str!("../../flows/verify.yaml");
const SKILL: &str = include_str!("../../../../skills/flow-verify-v1/SKILL.md");

#[test]
fn the_committed_driver_skill_is_what_the_ir_generates() {
    let flow = compile(VERIFY).unwrap();
    assert_eq!(skill_name(&flow).unwrap(), "flow-verify-v1");
    let generated = driver::generate(&flow).unwrap();
    assert_eq!(generated, SKILL, "skills/flow-verify-v1/SKILL.md is stale: run maestro flow driver-skill --out");
    assert!(SKILL.starts_with("---\n# Generated by maestro flow driver-skill from verify@1 ("));
    assert!(
        SKILL.contains("\nname: \"flow-verify-v1\"\ndescription: \"Drives an instance of the Maestro flow verify@1")
    );
    assert!(SKILL.contains(flow.hash()));
}

#[test]
fn verify_runs_pin_and_surface_then_check_then_exercise() {
    let flow = compile(VERIFY).unwrap();
    assert_eq!(steps(&flow), [vec!["pin", "surface"], vec!["check"], vec!["exercise"]]);
    let skill = driver::generate(&flow).unwrap();
    let at = |s: &str| skill.find(s).unwrap_or_else(|| panic!("no {s}"));
    assert!(at("### Step 1: `pin`, `surface`") < at("### Step 2: `check`"));
    assert!(at("### Step 2: `check`") < at("### Step 3: `exercise`"));
    assert!(skill.contains("- Applies only when `surface` is `declared`"));
    assert!(skill.contains("- Performer: `agent:verifier`, with the skill `dogfood`."));
    // The Codex brief is the agent's, embedded whole.
    let brief = maestro_flow::agents::find("verifier").unwrap().codex();
    assert!(skill.contains(&serde_json::to_string(&brief.message).unwrap()));
    assert!(skill.contains("the `Agent` tool with `subagent_type: \"verifier\"` (`.claude/agents/verifier.md`)"));
}

#[test]
fn the_steps_follow_the_ir_not_the_ids_or_the_definition() {
    // Declared, and named, against the order they run in.
    let flow = compile(
        "flow: order
version: 1
nodes:
  a: {class: work, verify: [x], needs: [b]}
  b: {class: work, verify: [x], needs: [c]}
  c: {class: choice, edges: {go: {guard: 'true'}, stop: {guard: 'true'}}}
  z: {class: work, verify: [x], switch: {on: c, case: go}}
  y: {class: work, verify: [x], needs: [loop]}
  m: {class: observe, run: [x], fresh_for: 1m, exit_map: {0: ok}, needs: [z]}
repeats:
  loop: {body: [m], max: 3}
",
    )
    .unwrap();
    assert_eq!(steps(&flow), [vec!["c"], vec!["b", "z"], vec!["a", "m"], vec!["y"]]);
    let skill = driver::generate(&flow).unwrap();
    let at = |s: &str| skill.find(s).unwrap_or_else(|| panic!("no {s}"));
    assert!(at("#### `c` (choice)") < at("#### `b` (work)"));
    assert!(at("#### `b` (work)") < at("#### `a` (work)"));
    assert!(at("#### `m` (observe)") < at("#### `y` (work)"));
    assert!(skill.contains("- Waits on: repeat `loop` to finish."));
    assert!(skill.contains("- In repeat `loop`: it runs once per iteration, at most 3"));
    assert!(skill.contains("- `loop`: `m`, at most 3 iterations."));
    assert!(skill.contains("pick one of its edges (`go`, `stop`)"));
    assert!(!skill.contains("## Agents"), "no agent performs this flow");
}

#[test]
fn a_skill_name_is_made_from_the_flow_name_and_version() {
    let flow = compile("flow: My_Flow..x\nversion: 12\nnodes:\n  a: {class: work, verify: [x]}\n").unwrap();
    assert_eq!(skill_name(&flow).unwrap(), "flow-my-flow-x-v12");
    let long = format!("flow: {}\nversion: 1\nnodes:\n  a: {{class: work, verify: [x]}}\n", "f".repeat(60));
    let e = skill_name(&compile(&long).unwrap()).unwrap_err();
    assert_eq!(e.code(), "skill_name_invalid");
}
